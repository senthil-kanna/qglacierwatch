"""Deterministic SYNTHETIC basin fixture for offline tests and demo mode.

Not real data. A toy degree-day snow model drives a two-reservoir runoff model so the series
has snowmelt and monsoon seasonality similar in shape to a Himalayan basin. Every file it writes
carries source="SYNTHETIC" and lives under data/synthetic/, separate from data/raw/.

Usage:
    python -m src.data.synthetic
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from src import config

SOURCE = "SYNTHETIC"


def generate(start: str = "2015-01-01", end: str = "2025-12-31", seed: int = 7) -> dict[str, pd.DataFrame]:
    rng = np.random.default_rng(seed)
    dates = pd.date_range(start, end, freq="D")
    n = len(dates)
    doy = dates.dayofyear.to_numpy()
    year_idx = (dates.year - dates.year[0]).to_numpy()

    # Temperature: seasonal cycle, slight warming trend, AR(1) weather noise.
    noise = np.zeros(n)
    for i in range(1, n):
        noise[i] = 0.8 * noise[i - 1] + rng.normal(0, 1.6)
    t_mean = 0.5 - 10.0 * np.cos(2 * np.pi * (doy - 15) / 365.25) + 0.05 * year_idx + noise
    t_min = t_mean - 5.5 - rng.gamma(2, 0.5, n)
    t_max = t_mean + 5.0 + rng.gamma(2, 0.5, n)

    # Precipitation: winter westerlies plus a stronger monsoon peak.
    wet_prob = 0.25 + 0.35 * np.exp(-(((doy - 210) / 35) ** 2)) + 0.15 * np.exp(-(((doy - 40) / 30) ** 2))
    wet = rng.random(n) < wet_prob
    precip = np.where(wet, rng.gamma(0.9, 8.0, n), 0.0)
    snowfall = np.where(t_mean < 0.5, precip, 0.0)
    rain = precip - snowfall

    # Degree-day snowpack (mm SWE) and snow-covered fraction.
    swe = np.zeros(n)
    melt = np.zeros(n)
    store = 150.0
    for i in range(n):
        potential = 4.0 * max(t_mean[i] + 2.0, 0.0)
        melt[i] = min(store + snowfall[i], potential)
        store = store + snowfall[i] - melt[i]
        swe[i] = store
    snow_frac = np.clip(0.08 + 0.85 * (1 - np.exp(-swe / 120.0)), 0, 1)

    # Two linear reservoirs (fast: rain+melt, slow: baseflow) -> discharge in m3/s.
    area_km2 = 3532.0
    to_m3s = area_km2 * 1e6 / 1000.0 / 86400.0  # mm/day over the basin -> m3/s
    fast = slow = 0.0
    q = np.zeros(n)
    for i in range(n):
        inflow = rain[i] + melt[i]
        fast += 0.6 * inflow
        slow += 0.4 * inflow
        out_fast, out_slow = 0.25 * fast, 0.02 * slow
        fast -= out_fast
        slow -= out_slow
        q[i] = 18.0 + (out_fast + out_slow) * to_m3s
    q = q * np.exp(rng.normal(0, 0.04, n))

    # MODIS-like cloud gaps: cloudier in monsoon, a few fully missing days.
    cloud = np.clip(0.3 + 0.5 * np.exp(-(((doy - 205) / 40) ** 2)) + rng.normal(0, 0.2, n), 0, 1)
    valid_frac = 1 - cloud
    snow_frac_basin = snow_frac * valid_frac
    snow_frac_valid = np.where(valid_frac >= 0.2, snow_frac, np.nan)
    ndsi_mean = np.where(valid_frac > 0, 10 + 60 * snow_frac + rng.normal(0, 3, n), np.nan)
    modis = pd.DataFrame(
        {
            "date": dates,
            "ndsi_mean": ndsi_mean,
            "snow_frac_basin": snow_frac_basin,
            "valid_frac": valid_frac,
            "snow_frac_valid": snow_frac_valid,
        }
    )
    modis = modis.drop(index=rng.choice(n, size=max(1, n // 200), replace=False)).reset_index(drop=True)

    era5 = pd.DataFrame(
        {
            "date": dates,
            "snow_depth_water_equivalent": swe,
            "snowfall_sum": snowfall,
            "snowmelt_sum": melt,
            "temperature_2m": t_mean,
            "temperature_2m_max": t_max,
            "temperature_2m_min": t_min,
            "total_precipitation_sum": precip,
        }
    )
    discharge = pd.DataFrame({"date": dates, "discharge_m3s": q, "source": SOURCE})
    return {"modis_snow": modis, "era5_land": era5, "discharge": discharge}


def write(out_dir: Path, **kwargs) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {}
    for name, df in generate(**kwargs).items():
        path = out_dir / f"{name}.parquet"
        df.to_parquet(path, index=False)
        paths[name] = path
    (out_dir / "README.txt").write_text(
        "SYNTHETIC data generated by src/data/synthetic.py for offline tests and demo mode. Not observations.\n"
    )
    return paths


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=config.raw_dir("demo"))
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()
    paths = write(args.out, seed=args.seed)
    print(f"Wrote SYNTHETIC fixture to {args.out}: {', '.join(p.name for p in paths.values())}")


if __name__ == "__main__":
    main()
